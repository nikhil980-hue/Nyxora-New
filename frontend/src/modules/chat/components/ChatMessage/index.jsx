  // ====================================================
  // SPEECH OUTPUT HELPERS
  // ====================================================

const cleanSpeechText = (
  value = ""
) => {
  let source = String(value || "");

  // Speech should communicate the answer, not its visual/technical
  // formatting. Remove presentation-only content before TTS.
  source = source
    // Fenced code and inline code.
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/`[^`]*`/g, " ")

    // Images and markdown links: keep useful link text only.
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")

    // Markdown headings/emphasis/quotes.
    .replace(/^\s{0,3}#{1,6}\s+/gm, "")
    .replace(/[*_~`>#]/g, " ")

    // Markdown table separator rows are never useful in speech.
    .replace(/^\s*\|?\s*:?-{2,}:?\s*(?:\|\s*:?-{2,}:?\s*)+\|?\s*$/gim, " ")

    // Table vertical separators should never be spoken as punctuation.
    .replace(/\|/g, " ")

    // Math delimiters / LaTeX control syntax. Keep readable text but do not
    // literally pronounce formatting commands such as \frac or \begin.
    .replace(/\$\$[\s\S]*?\$\$/g, " ")
    .replace(/\$([^$]+)\$/g, "$1")
    .replace(/\\(?:frac|sqrt|sum|int|text|mathrm|mathbf|left|right|begin|end|times|cdot|approx|neq|leq|geq)\b/g, " ")
    .replace(/[{}^_]/g, " ")

    // URLs, email addresses, citation/reference markers and raw HTML are
    // generally navigation/formatting noise in spoken conversation.
    .replace(/https?:\/\/\S+/gi, " ")
    .replace(/www\.\S+/gi, " ")
    .replace(/\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/(?:\[cite[^\]]*\]|\(cite[^)]*\))/gi, " ")

    // Remove emoji/pictographic symbols so TTS does not say things such as
    // "red heart", "fire emoji", etc.
    .replace(/[\p{Extended_Pictographic}\uFE0F\u200D]/gu, " ")

    // Remove decorative bullets/symbols that do not add meaning.
    .replace(/[•◦▪▫◾◽◆◇★☆✓✔✕✖→←↑↓⇒⇐]/g, " ")

    // Collapse punctuation-only runs and whitespace.
    .replace(/(?:[-–—_=~]){2,}/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  return source.slice(0, 12000);
};


  const getSpeechLanguage = (
    value = ""
  ) => {
    const source = String(value || "");
    const devanagari =
      (source.match(/[\\u0900-\\u097F]/g) || []).length;
    const letters =
      (source.match(/[A-Za-z\\u0900-\\u097F]/g) || []).length;

    return letters > 0 && devanagari / letters >= 0.15
      ? "hi-IN"
      : "en-IN";
  };


  const splitSpeechText = (value = "") => {
    const source = String(value || "").trim();

    if (!source) {
      return [];
    }

    const chunks = [];
    let remaining = source;

    while (remaining.length > NYXORA_SPEECH_CHUNK_SIZE) {
      const windowText = remaining.slice(0, NYXORA_SPEECH_CHUNK_SIZE);
      const minimumBoundary = Math.floor(NYXORA_SPEECH_CHUNK_SIZE * 0.55);

      let boundary = -1;

      for (let index = windowText.length - 1; index >= minimumBoundary; index -= 1) {
        if (/[.!?;:]/.test(windowText[index])) {
          boundary = index + 1;
          break;
        }
      }

      if (boundary < 0) {
        boundary = windowText.lastIndexOf(" ");
      }

      if (boundary <= 0) {
        boundary = NYXORA_SPEECH_CHUNK_SIZE;
      }

      chunks.push(remaining.slice(0, boundary).trim());
      remaining = remaining.slice(boundary).trim();
    }

    if (remaining) {
      chunks.push(remaining);
    }

    return chunks.filter(Boolean);
  };


  const getPreferredVoice = (voices, language) => {
    const normalizedLanguage = String(language || "").toLowerCase();
    const languagePrefix = normalizedLanguage.slice(0, 2);

    const matching = voices.filter((voice) => {
      const voiceLanguage = String(voice?.lang || "").toLowerCase();
      return (
        voiceLanguage === normalizedLanguage ||
        voiceLanguage.startsWith(`${languagePrefix}-`) ||
        voiceLanguage === languagePrefix
      );
    });

    if (!matching.length) {
      return null;
    }

    // Browser speech APIs do not expose a standard gender property, so we
    // deliberately prefer voices whose provider/name identifies them as
    // masculine. Exact known male voices receive the highest priority.
    const masculineExactSignals = [
      "microsoft ravi",
      "microsoft david",
      "microsoft mark",
      "microsoft guy",
      "google uk english male",
      "google us english male",
      "google english male",
      "david desktop",
      "mark desktop",
      "ravi",
      "david",
      "mark",
      "daniel",
      "george",
      "james",
      "guy",
    ];

    const masculineSignals = [
      "male",
      "man",
      "masculine",
      "natural male",
    ];

    const feminineSignals = [
      "female",
      "woman",
      "feminine",
      "zira",
      "samantha",
      "susan",
      "heera",
      "priya",
      "neerja",
      "aria",
      "jenny",
      "ava",
      "emma",
    ];

    const scoreVoice = (voice) => {
      const name = String(voice?.name || "").toLowerCase();
      const lang = String(voice?.lang || "").toLowerCase();
      let score = 0;

      if (lang === normalizedLanguage) score += 12;
      else if (lang.startsWith(`${languagePrefix}-`)) score += 8;

      if (voice?.localService) score += 5;

      masculineExactSignals.forEach((signal, index) => {
        if (name.includes(signal)) score += 100 - index * 2;
      });

      masculineSignals.forEach((signal) => {
        if (name.includes(signal)) score += 45;
      });

      feminineSignals.forEach((signal) => {
        if (name.includes(signal)) score -= 120;
      });

      if (name.includes("google") || name.includes("microsoft")) score += 3;
      if (name.includes("online") || name.includes("natural")) score += 2;

      return score;
    };

    return [...matching].sort((a, b) => scoreVoice(b) - scoreVoice(a))[0] || null;
  };


  const speakMessage = () => {
    if (!speechSupported) {
      if (speechConversationActive) {
        onSpeechEnd?.();
      }
      return;
    }

    const content = cleanSpeechText(text);

    if (!content) {
      if (speechConversationActive) {
        onSpeechEnd?.();
      }
      return;
    }

    try {
      const speechId = `nyxora-speech-${++nyxoraSpeechSequence}`;
      const language = getSpeechLanguage(content);
      const chunks = splitSpeechText(content);

      // A new response owns the global speech channel. Cancel only the
      // previous owner, then immediately replace the controller ownership
      // before its cancellation callbacks can affect the new response.
      if (nyxoraSpeechController.ownerId) {
        try {
          window.speechSynthesis.cancel();
        } catch {
          // Ignore cancellation errors from the browser speech engine.
        }
      }

      nyxoraSpeechController.ownerId = speechId;
      nyxoraSpeechController.utterance = null;
      speechInstanceIdRef.current = speechId;
      setIsSpeaking(true);

      const voices = window.speechSynthesis.getVoices();
      const preferredVoice = getPreferredVoice(voices, language);
      let chunkIndex = 0;

      const finishSpeech = () => {
        if (nyxoraSpeechController.ownerId !== speechId) {
          return;
        }

        nyxoraSpeechController.ownerId = null;
        nyxoraSpeechController.utterance = null;
        speechInstanceIdRef.current = null;
        setIsSpeaking(false);

        if (speechConversationActive) {
          onSpeechEnd?.();
        }
      };

      const speakNextChunk = () => {
        if (nyxoraSpeechController.ownerId !== speechId) {
          return;
        }

        if (chunkIndex >= chunks.length) {
          finishSpeech();
          return;
        }

        const utterance = new SpeechSynthesisUtterance(chunks[chunkIndex]);
        utterance.lang = language;
        utterance.rate = 1;
        utterance.pitch = 0.92;
        utterance.volume = 1;

        if (preferredVoice) {
          utterance.voice = preferredVoice;
        }

        nyxoraSpeechController.utterance = utterance;

        utterance.onend = () => {
          if (nyxoraSpeechController.ownerId !== speechId) {
            return;
          }

          chunkIndex += 1;
          speakNextChunk();
        };

        utterance.onerror = (event) => {
          if (nyxoraSpeechController.ownerId !== speechId) {
            return;
          }

          // "interrupted" is normally produced by an explicit cancellation.
          // If this utterance still owns the controller, it is a real failure.
          console.warn("Nyxora speech chunk error:", event?.error || "unknown");
          finishSpeech();
        };

        window.speechSynthesis.speak(utterance);
      };

      speakNextChunk();
    } catch (error) {
      console.error("Voice output error:", error);

      if (nyxoraSpeechController.ownerId === speechInstanceIdRef.current) {
        nyxoraSpeechController.ownerId = null;
        nyxoraSpeechController.utterance = null;
      }

      speechInstanceIdRef.current = null;
      setIsSpeaking(false);
    }
  };



  const stopSpeech = () => {
    if (!speechSupported) return;

    const ownsSpeech =
      speechInstanceIdRef.current &&
      nyxoraSpeechController.ownerId === speechInstanceIdRef.current;

    try {
      window.speechSynthesis.cancel();
    } catch {
      // Ignore browser speech cancellation errors.
    }

    if (ownsSpeech || window.speechSynthesis) {
      nyxoraSpeechController.ownerId = null;
      nyxoraSpeechController.utterance = null;
      speechInstanceIdRef.current = null;
      setIsSpeaking(false);
    }

    // A manual stop is an explicit end of the current voice answer.
    // Allow the voice-conversation controller to begin the next turn.
    if (speechConversationActive) {
      onSpeechEnd?.();
    }
  };


  const toggleSpeech = () => {
    if (!speechSupported) {
      window.alert(
        "Voice output is not supported by this browser."
      );
      return;
    }

    if (
      window.speechSynthesis.speaking ||
      window.speechSynthesis.pending
    ) {
      stopSpeech();
      return;
    }

    speakMessage();
  };


  // Automatically speak only the newly completed response while
  // Voice Mode is active. Existing/history responses are never
  // spoken when they first render.
  useEffect(() => {

    const responseComplete =
      Boolean(
        isAssistant &&
        isLastMessage &&
        !isGenerating &&
        String(text || "").trim()
      );

    const wasComplete =
      previousResponseCompleteRef.current;

    previousResponseCompleteRef.current =
      responseComplete;

    if (
      !speechConversationActive ||
      !responseComplete ||
      wasComplete
    ) {
      return;
    }

    // Do not start a new voice answer while another Nyxora response is
    // still being spoken. The global controller owns the current turn.
    if (
      window.speechSynthesis?.speaking ||
      window.speechSynthesis?.pending
    ) {
      return;
    }

    speakMessage();

  }, [
    voiceMode,
    jarvisMode,
    isAssistant,
    isLastMessage,
    isGenerating,
    text,
  ]);


  useEffect(() => {
    return () => {
      // Do not let an older ChatMessage instance cancel speech belonging to
      // the newer assistant response. This was the main source of truncated
      // multi-turn voice replies.
      if (
        speechInstanceIdRef.current &&
        nyxoraSpeechController.ownerId === speechInstanceIdRef.current
      ) {
        try {
          window.speechSynthesis?.cancel();
        } catch {
          // Ignore browser speech cancellation errors.
        }

        nyxoraSpeechController.ownerId = null;
        nyxoraSpeechController.utterance = null;
      }
    };
  }, []);


  const toggleFavorite =
    () => {

      const content =
        String(
          text || ""
        ).trim();


      if (!content) {

        return;

      }


      const saved =
        JSON.parse(
          localStorage.getItem(
            "nyxora_favorites"
          )
        ) || [];


      const exists =
        saved.includes(
          content
        );


      const updated =
        exists
          ? saved.filter(
              (item) =>
                item !== content
            )
          : [
              ...saved,
              content,
            ];


      localStorage.setItem(
        "nyxora_favorites",
        JSON.stringify(
          updated
        )
      );


      setIsFavorite(
        !exists
      );

    };


  // ====================================================
  // SAVE TO WORKSPACE
  // ====================================================

  const handleSaveToWorkspace =
    () => {

      if (
        !isAssistant ||
        !onSaveToWorkspace
      ) {

        return;

      }


      const content =
        String(
          text || ""
        ).trim();


      if (
        !content
      ) {

        return;

      }


onSaveToWorkspace({
  messageId: id,
  content,
  pdfRequested: Boolean(pdfRequested),
  notesImageRequested:
    Boolean(notesImageRequested),
  notesImageTopic:
    notesImageTopic,
});

  setIsSaved(true);

  window.setTimeout(() => {
    setIsSaved(false);
  }, 1600);
};

function getNotesImageTopic(
  value = ""
) {

  let topic =
    String(
      value || ""
    )
      .replace(
        /generate\s+pdf/iu,
        ""
      )
      .replace(
        /\bnotes?\b/iu,
        ""
      )
      .replace(
        /\b(?:and\s+)?add\s+(?:a\s+)?(?:relevant\s+)?(?:image|images|picture|pictures|photo|photos|visual|visuals|figure|figures|illustration|illustrations)\b/iu,
        ""
      )
      .replace(
        /\bfor\s+class\s+\d+(?:\s*[A-Za-z])?\b/iu,
        ""
      )
      .replace(
        /\bclass\s+\d+(?:\s*[A-Za-z])?\b/iu,
        ""
      )
      .replace(
        /\b(?:on|about|regarding)\b/iu,
        ""
      )
      .replace(
        /\s+/g,
        " "
      )
      .trim();

  return (
    topic ||
    String(value || "")
      .replace(/\s+/g, " ")
      .trim()
      .slice(0, 80)
  );

}

// ====================================================
// EXTRACT MULTIPLE RELEVANT NOTES IMAGE TOPICS
// ====================================================

function getNotesImageTopics(
  value = ""
) {

  const source =
    String(
      value || ""
    )
      .replace(
        /\r/g,
        ""
      )
      .trim();


  if (
    !source
  ) {

    return [];

  }


  const topics =
    [];


  const addTopic =
    (
      topic
    ) => {

      const cleanTopic =
        String(
          topic || ""
        )
          .replace(
            /\s+/g,
            " "
          )
          .trim()
          .replace(
            /^[#*\-\d.)\s]+/,
            ""
          )
          .replace(
            /[:：]\s*$/,
            ""
          )
          .trim()
          .slice(
            0,
            100
          );


      if (
        !cleanTopic
      ) {

        return;

      }


      /*
       * Ignore headings that are too generic.
       */

      if (
        /^(?:introduction|conclusion|summary|revision|references|contents|index|overview)$/iu.test(
          cleanTopic
        )
      ) {

        return;

      }


      /*
       * Ignore headings that are actually long
       * sentences instead of topics.
       */

      if (
        cleanTopic.split(
          /\s+/
        ).length > 10
      ) {

        return;

      }


      const exists =
        topics.some(
          (
            existing
          ) =>
            existing.toLowerCase() ===
            cleanTopic.toLowerCase()
        );


      if (
        !exists
      ) {

        topics.push(
          cleanTopic
        );

      }

    };


  const lines =
    source.split(
      "\n"
    );


  lines.forEach(
    (
      rawLine
    ) => {

      const line =
        String(
          rawLine || ""
        ).trim();


      if (
        !line
      ) {

        return;

      }


      /*
       * Markdown headings:
       *
       * # Chlorophyll
       * ## Leaf Anatomy
       */

      const markdownHeading =
        line.match(
          /^#{1,6}\s+(.+?)\s*$/u
        );


      if (
        markdownHeading
      ) {

        addTopic(
          markdownHeading[1]
        );

        return;

      }


      /*
       * Numbered headings:
       *
       * 1. Chlorophyll
       * 2. Chemical Equation
       */

      const numberedHeading =
        line.match(
          /^\d+\s*[.)-]\s+(.+?)\s*$/u
        );


      if (
        numberedHeading
      ) {

        const candidate =
          numberedHeading[1]
            .replace(
              /\s*:+\s*$/,
              ""
            )
            .trim();


        /*
         * Only treat it as a topic when it
         * looks like a heading rather than
         * a complete sentence.
         */

        if (
          candidate &&
          candidate.split(
            /\s+/
          ).length <= 10 &&
          !/[.!?]$/u.test(
            candidate
          )
        ) {

          addTopic(
            candidate
          );

        }

        return;

      }


      /*
       * Bold standalone headings:
       *
       * **Chlorophyll**
       * **Leaf Anatomy:**
       */

      const boldHeading =
        line.match(
          /^\*{1,2}([^*]+?)\*{1,2}\s*:?\s*$/u
        );


      if (
        boldHeading
      ) {

        addTopic(
          boldHeading[1]
        );

        return;

      }


      /*
       * Standalone "Topic:" / "Heading:"
       */

      const colonHeading =
        line.match(
          /^([A-Za-z\u0900-\u097F][A-Za-z0-9\u0900-\u097F &()\/,+\-]{2,80})\s*:\s*$/u
        );


      if (
        colonHeading
      ) {

        addTopic(
          colonHeading[1]
        );

      }

    }
  );


  /*
   * Limit automatic topic images.
   *
   * Five images keeps the PDF useful without
   * overwhelming the Notes pages.
   */

  if (
    topics.length >
    5
  ) {

    return topics.slice(
      0,
      5
    );

  }


  /*
   * Fallback for Notes that contain no
   * recognizable headings.
   */

  if (
    topics.length ===
    0
  ) {

    const fallbackTopic =
      getNotesImageTopic(
        source
      );


    if (
      fallbackTopic
    ) {

      addTopic(
        fallbackTopic
      );

    }

  }


  return topics.slice(
    0,
    5
  );

}

